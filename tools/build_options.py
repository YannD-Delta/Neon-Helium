"""Generate the theme settings files from tools/options_spec.yaml.

Outputs (all inside the theme folder):
  options.yaml              ThemeOptions presets and variables
  Localization/en_US.xaml   English labels (Playnite only loads theme translations when this file exists)
  Localization/fr_FR.xaml   French labels for ThemeOptions and the views
  thememodifier.yaml        ThemeModifier color pickers
  Presets/**/*.xaml         preset resource files (button, chip, animation and artwork looks)
  Presets/Colors/*.xaml     color profiles (color_profiles section, see tools/color_profiles.py)
  DerivedStyles/PlayButton.xaml  the default hero styles, between the generated markers

Types and defaults come from Constants.xaml. The script stops on any inconsistency.

Usage:
    python tools/build_options.py [--source source] [--check]

--check exits with an error when a generated file is missing or out of date (used by the linter and CI).
"""
