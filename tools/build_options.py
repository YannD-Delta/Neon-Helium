XAML_NS = "http://schemas.microsoft.com/winfx/2006/xaml"
SYS_NS = "clr-namespace:System;assembly=mscorlib"
KEY = "{%s}Key" % XAML_NS

# Constants.xaml element type -> ThemeOptions type name
TYPES = {
    "sys:Boolean": "Boolean", "sys:Double": "Double", "sys:Int32": "Int32", "sys:String": "String",
    "Visibility": "Visibility", "CornerRadius": "CornerRadius", "Thickness": "Thickness",
    "Color": "Color", "SolidColorBrush": "SolidColorBrush",
}
SLIDER_TYPES = {"Double", "Int32", "CornerRadius"}
PLAIN_TYPES = {"Boolean", "Visibility", "String"}
PRESET_CONSTANT_TYPES = {"Boolean", "String", "Double", "Int32", "Color", "Thickness", "CornerRadius", "SolidColorBrush"}
MODIFIER_TYPES = {"Color", "SolidColorBrush"}

GENERATED = "Generated by tools/build_options.py from tools/options_spec.yaml. Do not edit by hand."


class SpecError(Exception):
    pass


def element_type(element):
    tag = element.tag
    if tag.startswith("{"):
        namespace, name = tag[1:].split("}")
        return "sys:" + name if namespace == SYS_NS else name
    return tag


def read_constants(source: Path):
    """Map key -> (ThemeOptions type or None, default text) for every keyed resource in Constants.xaml."""
    root = ET.fromstring((source / "Constants.xaml").read_text(encoding="utf-8-sig"))
    result = {}
    for element in root.iter():
        key = element.get(KEY)
        if not key:
            continue
        kind = TYPES.get(element_type(element))
        value = element.get("Color") if kind == "SolidColorBrush" else (element.text or "").strip()
        result[key] = (kind, value)
    return result


def normalize(kind, value):
    if kind == "Boolean":
        if str(value).lower() not in ("true", "false"):
            raise SpecError(f"not a boolean: {value!r}")
        return "True" if str(value).lower() == "true" else "False"
    if isinstance(value, bool):
        raise SpecError(f"boolean value {value!r} for a {kind}")
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    return str(value)


def q(text) -> str:
    """Single-quoted YAML scalar."""
    return "'" + str(text).replace("'", "''") + "'"


def loc_key(*parts) -> str:
    return "LOCHND" + "".join(parts)



CAPTION_PREFIX = "\u2003\u2003\u21b3 "  # indent + arrow, so captions don't read as section headers
CAPTION_MAX = 95


def split_sentences(text):
    return [part.strip() for part in re.split(r"(?<=[.!?])\s+", text.strip()) if part.strip()]


def caption_rows(key, tip, labels, english):
    """One Theme Options Header row per sentence of the tip: the Desktop settings view shows
    Header titles but no descriptions, and its text does not wrap."""
    french, other = split_sentences(tip["fr"]), split_sentences(tip["en"])
    if len(french) != len(other):
        raise SpecError(f"tip {key}: French and English must have the same number of sentences")
    rows = []
    for index, (fr_text, en_text) in enumerate(zip(french, other), 1):
        for text in (fr_text, en_text):
            if len(text) > CAPTION_MAX:
                raise SpecError(f"tip {key}: sentence longer than {CAPTION_MAX} characters "
                                f"(Theme Options does not wrap captions): {text}")
        name = f"Caption{key}{index}"
        lkey = loc_key("Caption", f"{key}{index}")
        labels[lkey] = CAPTION_PREFIX + fr_text
        english[lkey] = CAPTION_PREFIX + en_text
        rows += [f"    {name}:", f"        Title: {q(CAPTION_PREFIX + en_text)}", f"        LocKey: {lkey}",
                 "        Type: Header"]
    return rows

def build_options(spec, constants, source: Path):
    lines = [f"# {GENERATED}", "# Read by the ThemeOptions extension (https://codeberg.org/ashpynov/ThemeOptions).", ""]
    labels = {}
    english = {}
    used_keys = set()

    lines.append("Presets:")
    for group in spec["presets"]:
        gid = group["group"]
        gkey = loc_key("Preset", gid)
        labels[gkey] = group["fr"]
        english[gkey] = group["en"]
        lines += [f"    {gid}:", f"        Name: {q(group['en'])}", f"        LocKey: {gkey}", "        Presets:"]
        ids = [option["id"] for option in group["options"]]
        if ids[0] != "Default" or len(set(ids)) != len(ids):
            raise SpecError(f"preset group {gid}: the first option must be Default and ids must be unique")
        for option in group["options"]:
            okey = loc_key("Preset", gid, option["id"])
            labels[okey] = option["fr"]
            english[okey] = option["en"]
            lines += [f"            {option['id']}:", f"                Name: {q(option['en'])}", f"                LocKey: {okey}"]
            preview = f"Presets/Previews/{gid}_{option['id']}.png"
            if (source / preview).is_file():
                # shown by Theme Options while the mouse is over this choice (tools/make_previews.py)
                lines.append(f"                Preview: {q(preview.replace('/', chr(92)))}")
            if group.get("restart"):
                lines.append("                NeedRestart: True")
            files = option.get("files") or []
            if files:
                lines.append("                Files:")
                for file in files:
                    if not (source / file).is_file():
                        raise SpecError(f"preset {gid}.{option['id']}: missing file {file}")
                    lines.append(f"                    - {q(file.replace('/', chr(92)))}")
            consts = option.get("constants") or {}
            if consts:
                lines.append("                Constants:")
                for key, value in consts.items():
                    kind = constants.get(key, (None, None))[0]
                    if kind not in PRESET_CONSTANT_TYPES:
                        raise SpecError(f"preset {gid}.{option['id']}: {key} is undefined or has an unsupported type ({kind})")
                    used_keys.add(key)
                    lines += [f"                    {key}:", f"                        Type: {kind}",
                              f"                        Value: {q(normalize(kind, value))}"]

    variable_keys = {entry["key"] for entry in spec["variables"] if "key" in entry}
    overlap = sorted(used_keys & variable_keys)
    if overlap:
        raise SpecError("preset constants must not be variables (Theme Options saves every value on exit, "
                        "the preset value would stick as a user setting): " + ", ".join(overlap))

    lines += ["", "Variables:"]
    seen = set()

    def header_rows(entry, name):
        key = loc_key("Header", entry["header"])
        labels[key] = entry["fr"]
        english[key] = entry["en"]
        return [f"    {name}:", f"        Title: {q(entry['en'])}", f"        LocKey: {key}", "        Type: Header"]

    def variable_rows(entry, with_captions):
        extra = set(entry) - {"key", "en", "fr", "range"}
        if extra or not {"key", "en", "fr"} <= set(entry):
            raise SpecError(f"bad variable entry (quote values that contain commas): {entry}")
        key = entry["key"]
        if key in seen:
            raise SpecError(f"variable {key} is listed twice")
        seen.add(key)
        kind, default = constants.get(key, (None, None))
        if kind is None:
            raise SpecError(f"variable {key} is not defined in Constants.xaml or has an unsupported type")
        default = normalize(kind, default)
        lkey = loc_key("Opt", key)
        labels[lkey] = entry["fr"]
        english[lkey] = entry["en"]
        rows = [f"    {key}:", f"        Title: {q(entry['en'])}", f"        LocKey: {lkey}",
                f"        Type: {kind}", f"        Default: {q(default)}"]
        tip = (spec.get("tips") or {}).get(key)
        if tip:
            # Theme Options keeps Description in its model but never displays it; the views
            # shows the tooltip, and caption rows (below) show the text in Theme Options.
            rows.append(f"        Description: {q(tip['en'])}")
            labels[loc_key("Tip", key)] = tip["fr"]
            english[loc_key("Tip", key)] = tip["en"]
        if kind in SLIDER_TYPES:
            if "range" not in entry:
                raise SpecError(f"variable {key} ({kind}) needs a range")
            low, high = entry["range"]
            number = float(default)
            if not number.is_integer() or not low <= number <= high:
                raise SpecError(f"variable {key}: default {default} must be a whole number within {low}..{high}")
            step = 1 if high - low <= 1000 else 10
            rows += ["        Slider:", f"            Min: {q(low)}", f"            Max: {q(high)}", f"            Step: {q(step)}"]
        elif kind not in PLAIN_TYPES:
            raise SpecError(f"variable {key}: type {kind} cannot be a ThemeOptions variable")
        elif "range" in entry:
            raise SpecError(f"variable {key}: a range makes no sense for {kind}")
        if tip and with_captions:
            rows += caption_rows(key, tip, labels, english)
        return rows

    # every setting is listed with its group header and caption rows; a header with no setting under it
    # is left out
    pending = None
    for entry in spec["variables"]:
        if "header" in entry:
            pending = entry
            continue
        if pending:
            lines += header_rows(pending, "Header" + pending["header"])
            pending = None
        lines += variable_rows(entry, True)
    unknown_tips = sorted(set(spec.get("tips") or {}) - seen)
    if unknown_tips:
        raise SpecError("tips for keys that are not variables: " + ", ".join(unknown_tips))
    return "\n".join(lines) + "\n", {"fr": labels, "en": english}, seen | used_keys


def build_localization(spec, labels, constants, language="fr"):
    for key in spec.get("strings", {}):
        if key not in constants:
            raise SpecError(f"string {key} needs its English text in Constants.xaml")
    entries = {**{k: v[language] for k, v in spec.get("strings", {}).items()}, **labels}
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {GENERATED} -->",
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:sys="clr-namespace:System;assembly=mscorlib">',
    ]
    for key, text in entries.items():
        lines.append(f'    <sys:String x:Key="{key}">{escape(str(text))}</sys:String>')
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


def build_modifier(spec, constants):
    lines = [f"# {GENERATED}", "# Colors only: the other settings are in options.yaml (ThemeOptions).", "Constants:"]
    for entry in spec["colors"]:
        if isinstance(entry, str):
            lines.append(f'    - "{entry}"')
            continue
        key, label = entry
        if constants.get(key, (None,))[0] not in MODIFIER_TYPES:
            raise SpecError(f"color {key} is not a Color or SolidColorBrush in Constants.xaml")
        lines.append(f"    - {key}: {q(label)}")
    return "\n".join(lines) + "\n"


