# DerivedStyles/PlayButton.xaml: the default hero styles (the Dune button, Pills chip and Smooth fade presets)
BEGIN = "    <!-- BEGIN generated hero styles: edit tools/build_options.py, then run it. -->\n"
END = "    <!-- END generated hero styles -->\n"


def play_button_file(source: Path):
    """DerivedStyles/PlayButton.xaml with the default hero styles between the markers."""
    text = (source / "DerivedStyles" / "PlayButton.xaml").read_text(encoding="utf-8-sig")
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SpecError("DerivedStyles/PlayButton.xaml must contain the generated hero styles markers once")
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    body = hero_buttons("Dune") + "\n" + hero_chips("Pills") + "\n" + hero_fade("Smooth")
    return head + BEGIN + body + END + tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", default="source")
    parser.add_argument("--spec", default=str(Path(__file__).with_name("options_spec.yaml")))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = Path(args.source)

    try:
        spec = yaml.safe_load(Path(args.spec).read_text(encoding="utf-8"))
        constants = read_constants(source)
        add_color_profile_group(spec)
        outputs = {"DerivedStyles/PlayButton.xaml": play_button_file(source), **preset_files(),
                   **color_profile_files(spec, source)}
        if not args.check:
            # preset files must exist before the preset file check in build_options runs
            for name, content in outputs.items():
                path = source / name
                if not path.exists() or path.read_text(encoding="utf-8-sig") != content:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(content, encoding="utf-8")
                    print(f"wrote {path}")
        options, labels, _ = build_options(spec, constants, source)
        outputs["options.yaml"] = options
        # Playnite loads Localization/<language>.xaml for themes only when en_US.xaml exists.
        outputs["Localization/en_US.xaml"] = build_localization(spec, labels["en"], constants, "en")
        outputs["Localization/fr_FR.xaml"] = build_localization(spec, labels["fr"], constants, "fr")
        outputs["thememodifier.yaml"] = build_modifier(spec, constants)
    except (SpecError, KeyError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    stale = []
    for name, content in outputs.items():
        path = source / name
        current = path.read_text(encoding="utf-8-sig") if path.exists() else None
        if current != content:
            if args.check:
                stale.append(name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
                print(f"wrote {path}")
    if stale:
        print("error: out of date, run python tools/build_options.py: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
