FADE_LOOKS = {"Smooth": ("0:0:0.45", "16"), "Fast": ("0:0:0.2", "8"), "Off": None}


def hero_fade(name):
    look = FADE_LOOKS[name]
    if look is None:
        return '    <Style x:Key="HeroFadeInStyle" TargetType="{x:Type FrameworkElement}" />\n'
    duration, offset = look
    ease = """                            <DoubleAnimation.EasingFunction>
                                <CubicEase EasingMode="EaseOut" />
                            </DoubleAnimation.EasingFunction>
"""
    return f"""    <!--
        Fade and slide in when the selected game changes (Binding.TargetUpdated).
        The element must carry its own local TranslateTransform: a transform set by a style
        setter is frozen and cannot be animated.
    -->
    <Style x:Key="HeroFadeInStyle" TargetType="{{x:Type FrameworkElement}}">
        <Style.Triggers>
            <EventTrigger RoutedEvent="Binding.TargetUpdated">
                <BeginStoryboard>
                    <Storyboard>
                        <DoubleAnimation Storyboard.TargetProperty="Opacity" From="0" To="1" Duration="{duration}">
{ease}                        </DoubleAnimation>
                        <DoubleAnimation Storyboard.TargetProperty="(UIElement.RenderTransform).(TranslateTransform.Y)" From="{offset}" To="0" Duration="{duration}">
{ease}                        </DoubleAnimation>
                    </Storyboard>
                </BeginStoryboard>
            </EventTrigger>
        </Style.Triggers>
    </Style>
"""


def resource_file(body, note):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {GENERATED} {note} -->\n"
            '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
            '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n\n'
            + body + "</ResourceDictionary>\n")


def preset_files():
    files = {}
    for name in BUTTON_LOOKS:
        files[f"Presets/Buttons/{name}.xaml"] = resource_file(hero_buttons(name), f"Play button style: {name}.")
    for name in CHIP_LOOKS:
        files[f"Presets/Chips/{name}.xaml"] = resource_file(hero_chips(name), f"Information chips: {name}.")
    files["Presets/Animations/Fast.xaml"] = resource_file(hero_fade("Fast"), "Animations: fast.")
    files["Presets/Animations/Off.xaml"] = resource_file(hero_fade("Off"), "Animations: off.")
    files["Presets/Background/SoftBlur.xaml"] = resource_file(
        '    <BlurEffect x:Key="HeroBackgroundEffect" Radius="8" KernelType="Gaussian" RenderingBias="Performance" />\n', "Artwork: soft blur.")
    files["Presets/Background/StrongBlur.xaml"] = resource_file(
        '    <BlurEffect x:Key="HeroBackgroundEffect" Radius="22" KernelType="Gaussian" RenderingBias="Performance" />\n', "Artwork: strong blur.")
    for name, key, value in [("AlignTop", "DetailsViewBackgroundVerticalAlignment", "Top"),
                             ("AlignBottom", "DetailsViewBackgroundVerticalAlignment", "Bottom"),
                             ("AlignCenter", "DetailsViewBackgroundHorizontalAlignment", "Center"),
                             ("AlignRight", "DetailsViewBackgroundHorizontalAlignment", "Right")]:
        kind = "VerticalAlignment" if "Vertical" in key else "HorizontalAlignment"
        files[f"Presets/Background/{name}.xaml"] = resource_file(
            f'    <{kind} x:Key="{key}">{value}</{kind}>\n', f"Artwork position: {value}.")
    return files



def add_color_profile_group(spec):
    """Turn the color_profiles section into a preset group placed before insert_before."""
    section = spec.get("color_profiles")
    if not section:
        return
    group = {"group": "ColorProfile", "en": section["group"]["en"], "fr": section["group"]["fr"], "restart": True,
             "options": [{"id": "Default", "en": section["default"]["en"], "fr": section["default"]["fr"]}]}
    for profile in section["profiles"]:
        group["options"].append({"id": profile["id"], "en": profile["en"], "fr": profile["fr"],
                                 "files": [f"Presets/Colors/{profile['id']}.xaml"]})
    names = [g["group"] for g in spec["presets"]]
    where = names.index(section["insert_before"]) if section.get("insert_before") in names else len(names)
    spec["presets"].insert(where, group)


def color_profile_files(spec, source: Path):
    section = spec.get("color_profiles")
    if not section:
        return {}
    constants_text = (source / "Constants.xaml").read_text(encoding="utf-8-sig")
    expected = set(color_profiles.literal_color_keys(constants_text))
    files = {}
    for profile in section["profiles"]:
        derived = set(color_profiles.derive(profile["palette"]))
        if derived != expected:
            raise SpecError(f"color profile {profile['id']}: Constants.xaml colors not covered: "
                            f"{sorted(expected - derived)}; unknown: {sorted(derived - expected)} (tools/color_profiles.py)")
        files[f"Presets/Colors/{profile['id']}.xaml"] = color_profiles.profile_file(profile, constants_text, GENERATED)
    return files

